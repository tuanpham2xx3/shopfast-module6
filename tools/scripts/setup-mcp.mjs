import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parse } from "smol-toml";
const root = fileURLToPath(new URL("../../", import.meta.url));
const configPath = path.join(root, ".codex/config.toml");
await mkdir(path.dirname(configPath), { recursive: true });
let current = "";
try {
  current = await readFile(configPath, "utf8");
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
const config = parse(current);
if (config.mcp_servers?.context7) {
  console.log("Context7 project config already exists; preserved.");
} else {
  const entry = path.join(
    root,
    "tools/node_modules/@upstash/context7-mcp/dist/index.js",
  );
  const added = `\n# Generated by tools/scripts/setup-mcp.mjs for this checkout.\n[mcp_servers.context7]\ncommand = ${JSON.stringify(process.execPath)}\nargs = [${JSON.stringify(entry)}]\nstartup_timeout_sec = 30\ntool_timeout_sec = 40\n`;
  parse(current + added);
  await writeFile(configPath, current + added);
  console.log(
    `Configured Context7 in ${configPath}; existing settings preserved.`,
  );
}
